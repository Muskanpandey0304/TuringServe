"""Builds benchmarks/REPORT.md and the charts ONLY from the result JSON files (ARCH 10.9).

  python -m benchmarks.make_report [--results benchmarks/results] [--out benchmarks/REPORT.md]
"""

from __future__ import annotations

import argparse
import glob
import json
import os
from collections import defaultdict

VLLM_ISSUE_PREFILL = {8000: ("10.2 s", "vLLM-latest default backend, T4, Qwen2.5-1.5B (issue #60821)"),
                      "flashinfer": "1.1 s with FlashInfer (disabled on SM75 by default)"}


def load_all(results_dir):
    runs = []
    for path in sorted(glob.glob(os.path.join(results_dir, "*.json"))):
        try:
            d = json.load(open(path))
        except (OSError, json.JSONDecodeError):
            continue
        if "meta" in d and "runs" in d:
            d["_file"] = os.path.basename(path)
            runs.append(d)
    return runs


def table(rows, headers):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def fmt(x, d=2):
    return "n/a" if x != x else f"{x:.{d}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="benchmarks/results")
    ap.add_argument("--out", default="benchmarks/REPORT.md")
    ap.add_argument("--figures", default="benchmarks/figures")
    a = ap.parse_args()
    runs = load_all(a.results)
    os.makedirs(a.figures, exist_ok=True)
    lines = ["# TuringServe benchmark report", "",
             "_Generated by `benchmarks/make_report.py` from the JSON files in `benchmarks/results/`. "
             "No number below is typed by hand._", ""]
    env = [(r["meta"].get("label"), r["meta"].get("engine"), r["meta"].get("gpu", "?").replace("\n", " "),
            r["meta"].get("git_commit"), r["meta"].get("dataset"), r["meta"].get("start_time", "")[:10])
           for r in runs]
    lines += ["## Environment", "", table(env, ["label", "engine", "GPU / driver", "commit",
                                                 "workload", "date"]), ""]
    by_work = defaultdict(list)
    for r in runs:
        by_work[r["meta"]["dataset"]].append(r)

    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        plt = None

    for work, rs in by_work.items():
        lines += [f"## Workload: {work}", ""]
        rows = []
        for r in rs:
            for run in r["runs"]:
                m = run["median"]
                rows.append([r["meta"]["engine"], r["meta"].get("label"), run["kind"],
                             run["level"], fmt(m["output_throughput_tok_s"], 1),
                             fmt(m["ttft"]["p50"], 3), fmt(m["ttft"]["p90"], 3), fmt(m["ttft"]["p99"], 3),
                             fmt(m["tpot"]["p50"] * 1000, 1), fmt(m["tpot"]["p90"] * 1000, 1),
                             fmt(m["tpot"]["p99"] * 1000, 1), f"{m['goodput_fraction']:.0%}",
                             f"{m['goodput_rps']:.2f}", m["errors"]])
        lines += [table(rows, ["engine", "label", "mode", "level", "out tok/s", "TTFT p50 (s)",
                               "p90", "p99", "TPOT p50 (ms)", "p90", "p99", "goodput", "goodput rps",
                               "errors"]), ""]
        if work == "prefill":
            lines += ["### Prefill TTFT next to the vLLM numbers", "",
                      "vLLM latest, default attention backend on a T4, 8,000-token prompt: "
                      "**10.2 s**; with FlashInfer 1.1 s (vLLM issue #60821). Re-measure right "
                      "before publishing (PR #55380 may change this).", ""]
        if plt is not None:
            for metric, ylabel, fn in (("output_throughput_tok_s", "output tokens/s", "throughput"),
                                       ("ttft_p90", "TTFT p90 (s)", "ttft_p90")):
                fig, ax = plt.subplots(figsize=(6, 3.6))
                plotted = False
                for r in rs:
                    pts = [(run["level"], run["median"]["output_throughput_tok_s"] if metric ==
                            "output_throughput_tok_s" else run["median"]["ttft"]["p90"])
                           for run in r["runs"] if run["kind"] == "concurrency"]
                    if pts:
                        ax.plot(*zip(*sorted(pts), strict=False), marker="o",
                                label=f"{r['meta']['engine']} {r['meta'].get('label', '')}")
                        plotted = True
                if plotted:
                    ax.set_xscale("log", base=2)
                    ax.set_xlabel("concurrent clients")
                    ax.set_ylabel(ylabel)
                    ax.legend(fontsize=7)
                    fig.tight_layout()
                    fig.savefig(os.path.join(a.figures, f"{work}_{fn}.png"), dpi=130)
                    lines += [f"![{work} {fn}](figures/{work}_{fn}.png)", ""]
                plt.close(fig)

    # offline + quality + ablation files written by other scripts
    off = [json.load(open(p)) for p in glob.glob(os.path.join(a.results, "offline_*.json"))]
    if off:
        lines += ["## Offline throughput (fixed 128 output tokens)", "",
                  table([[o["engine"], o["gpu"], o["num_prompts"], fmt(o["seconds"], 1),
                          fmt(o["tok_per_s"], 1)] for o in off],
                        ["engine", "GPU", "prompts", "seconds", "tok/s"]), ""]
    quality = [json.load(open(p)) for p in glob.glob(os.path.join(a.results, "ppl_*.json"))]
    if quality:
        lines += ["## Perplexity (WikiText-2, window 1024, stride 512)", "",
                  table([[q["engine"], q["dtype"], "int8" if q["int8"] else "-",
                          os.path.basename(q["model"].rstrip("/")), fmt(q["ppl"], 4)] for q in quality],
                        ["engine", "dtype", "quant", "model", "ppl"]), ""]
    lines += ["## Limitations", "",
              "Laptop (GTX 1650, no tensor cores) numbers are for correctness only; every published "
              "performance number comes from the Kaggle T4. T4 clocks throttle at its 70 W cap, so "
              "runs are medians of 3 after warm-up.", ""]
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("wrote", a.out, f"({len(runs)} result files)")


if __name__ == "__main__":
    main()
