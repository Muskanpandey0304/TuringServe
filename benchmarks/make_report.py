"""Builds benchmarks/REPORT.md and the charts ONLY from the result JSON files (ARCH 10.9).

  python -m benchmarks.make_report [--results benchmarks/results] [--out benchmarks/REPORT.md]

Result files are grouped by their label (see classify): the main ShareGPT comparison, cold prefill, speculative
decoding, Autopilot, ramp and the Hugging Face smoke run each get their own section. Soak and chaos output is read from
<results>/soak_chaos/, the Autopilot decision log from <results>/autopilot/, quality files from <results>/quality/.
"""

from __future__ import annotations

import argparse
import glob
import json
import os
from collections import Counter, defaultdict

VLLM_ISSUE_PREFILL = ("10.2 s", "vLLM-latest default backend, T4, Qwen2.5-1.5B (issue #60821); "
                      "1.1 s with FlashInfer, which is disabled on SM75 by default")
ENGINES = ["turingserve", "vllm", "vllm-tuned", "vllm-flex", "vllm-flashinfer", "llamacpp", "hf"]
NAMES = {"turingserve": "TuringServe", "vllm": "vLLM", "vllm-tuned": "vLLM (batch 16384)", "vllm-flex": "vLLM FLEX_ATTENTION",
         "vllm-flashinfer": "vLLM FLASHINFER", "llamacpp": "llama.cpp", "hf": "Hugging Face"}


def load_all(results_dir):
    runs = []
    for path in sorted(glob.glob(os.path.join(results_dir, "*.json"))):
        try:
            d = json.load(open(path))
        except (OSError, json.JSONDecodeError):
            continue
        if isinstance(d, dict) and "meta" in d and "runs" in d:
            d["_file"] = os.path.basename(path)
            runs.append(d)
    return runs


def table(rows, headers):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def fmt(x, d=2):
    return "n/a" if x is None or x != x else f"{x:.{d}f}"


def classify(r):
    label = r["meta"].get("label") or ""
    ds = r["meta"].get("dataset")
    if ds == "prefill":
        return "prefill_cold" if label.endswith("prefill-cold") else "other"
    if label.startswith("spec-"):
        return "spec"
    if label.startswith("autopilot-"):
        return "autopilot"
    if "ramp" in label:
        return "ramp"
    if label.startswith("hf-baseline"):
        return "hf_smoke"
    if ds == "sharegpt" and label.startswith("t4-1.5b"):
        return "main"
    return "other"


def p(d, k):
    return (d.get(k) or float("nan"))


def sample_size(r):
    a = r["meta"].get("args", {})
    return f"{a.get('num_prompts', '?')}x{a.get('repeat', '?')}"


def prefill_by_length(r):
    """Median TTFT in ms per prompt length from the per-request records of the first run."""
    by = defaultdict(list)
    for q in r["runs"][0].get("requests", []):
        if q.get("first") and not q.get("error") and q.get("prompt_tokens"):
            by[q["prompt_tokens"]].append((q["first"] - q["send"]) * 1000)
    return {L: sorted(v)[len(v) // 2] for L, v in by.items()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="benchmarks/results")
    ap.add_argument("--out", default="benchmarks/REPORT.md")
    ap.add_argument("--figures", default="benchmarks/figures")
    a = ap.parse_args()
    runs = load_all(a.results)
    os.makedirs(a.figures, exist_ok=True)
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        plt = None

    groups = defaultdict(list)
    for r in runs:
        groups[classify(r)].append(r)

    def save_fig(fig, name):
        fig.tight_layout()
        fig.savefig(os.path.join(a.figures, name), dpi=130)
        plt.close(fig)

    L = ["# TuringServe benchmark report", "",
         "_Generated by `benchmarks/make_report.py` from the JSON files in `benchmarks/results/`. "
         "No number below is typed by hand. Method, run sizes and known limits: "
         "[docs/benchmark_methodology.md](../docs/benchmark_methodology.md)._", ""]

    # ---- environment / provenance
    prov = Counter()
    for r in runs:
        m = r["meta"]
        prov[(NAMES.get(m.get("engine"), m.get("engine")), (m.get("gpu") or "?").splitlines()[0],
              m.get("git_commit"), (m.get("start_time") or "")[:10])] += 1
    L += ["## Environment", "",
          table([[e, g, c, d, n] for (e, g, c, d), n in sorted(prov.items(), key=lambda x: (x[0][3], x[0][0]))],
                ["engine", "GPU / driver", "commit", "date", "result files"]),
          "", "All numbers are from one Kaggle Tesla T4 (sm_75, 15 GiB), Qwen2.5-1.5B-Instruct fp16 unless stated. "
          "TuringServe runs use torch 2.6.0+cu124 / Triton 3.2.0; the vLLM runs use vLLM 0.33.0 / torch 2.14.0+cu130 "
          "with its TRITON_ATTN backend. Commit hashes in the older files predate a history rewrite (same content; "
          "see the methodology document).", ""]

    # ---- main ShareGPT comparison
    main_runs = groups.get("main", [])
    if main_runs:
        stats = defaultdict(dict)       # engine -> level -> (median stats, sample size)
        for r in main_runs:
            for run in r["runs"]:
                if run["kind"] == "concurrency":
                    stats[r["meta"]["engine"]][run["level"]] = (run["median"], sample_size(r))
        engines = [e for e in ENGINES if e in stats]
        levels = sorted({lv for e in engines for lv in stats[e]})
        L += ["## ShareGPT throughput and latency vs concurrency", "",
              "Output tokens per second (higher is better); `ignore_eos` so every request generates its full reference "
              "length. Sample size (prompts x repetitions) differs per engine and level; see the second table.", ""]
        rows = []
        for lv in levels:
            row = [lv] + [fmt(stats[e][lv][0]["output_throughput_tok_s"], 1) if lv in stats[e] else "-" for e in engines]
            if "turingserve" in engines and "turingserve" in stats and lv in stats["turingserve"]:
                ts = stats["turingserve"][lv][0]["output_throughput_tok_s"]
                for e in engines:
                    if e != "turingserve":
                        row.append(f"{ts / stats[e][lv][0]['output_throughput_tok_s']:.2f}x" if lv in stats[e] else "-")
            rows.append(row)
        heads = ["concurrency"] + [NAMES[e] for e in engines]
        if "turingserve" in engines:
            heads += [f"TuringServe / {NAMES[e]}" for e in engines if e != "turingserve"]
        L += [table(rows, heads), ""]
        rows = []
        for lv in levels:
            for e in engines:
                if lv in stats[e]:
                    m, n = stats[e][lv]
                    rows.append([lv, NAMES[e], fmt(m["ttft"]["p50"] * 1000, 0), fmt(m["ttft"]["p90"] * 1000, 0),
                                 fmt(m["tpot"]["p50"] * 1000, 1), fmt(m["tpot"]["p90"] * 1000, 1),
                                 f"{m['goodput_fraction']:.0%}", m["errors"], n])
        L += [table(rows, ["concurrency", "engine", "TTFT p50 (ms)", "TTFT p90 (ms)", "TPOT p50 (ms)", "TPOT p90 (ms)",
                           "goodput", "errors", "prompts x reps"]), ""]
        if plt is not None:
            for metric, ylabel, name in (("thr", "output tokens/s", "main_throughput.png"),
                                         ("ttft", "TTFT p90 (s)", "main_ttft_p90.png")):
                fig, ax = plt.subplots(figsize=(6, 3.6))
                for e in engines:
                    pts = sorted((lv, (s[0]["output_throughput_tok_s"] if metric == "thr" else s[0]["ttft"]["p90"]))
                                 for lv, s in stats[e].items())
                    if len(pts) > 1:
                        ax.plot(*zip(*pts, strict=False), marker="o", label=NAMES[e])
                ax.set_xscale("log", base=2)
                ax.set_xlabel("concurrent clients")
                ax.set_ylabel(ylabel)
                ax.legend(fontsize=8)
                save_fig(fig, name)
                L += [f"![{ylabel} vs concurrency](figures/{name})", ""]

    # ---- cold prefill
    pre = groups.get("prefill_cold", [])
    if pre:
        per = {r["meta"]["engine"]: prefill_by_length(r) for r in pre}
        engines = [e for e in ENGINES if e in per]
        lengths = sorted({n for e in engines for n in per[e]})
        L += ["## Cold prefill (prefix caching off): time to first token by prompt length", "",
              "One request at a time, 5 prompts per length, 3 repetitions. TuringServe ran with `--no-prefix-caching`, "
              "vLLM with `--no-enable-prefix-caching` and llama.cpp with `--cache-ram 0 --no-cache-prompt`; the spread "
              "inside each length is under a few percent, so every "
              "request was cold.", ""]
        rows = []
        for n in lengths:
            row = [n] + [f"{per[e][n]:,.0f} ms ({n / (per[e][n] / 1000):,.0f} tok/s)" if n in per[e] else "-" for e in engines]
            if "turingserve" in per and n in per["turingserve"]:
                for e in engines:
                    if e != "turingserve":
                        row.append(f"{per[e][n] / per['turingserve'][n]:.1f}x" if n in per[e] else "-")
            rows.append(row)
        heads = ["prompt tokens"] + [NAMES[e] for e in engines]
        if "turingserve" in per:
            heads += [f"TuringServe speed-up vs {NAMES[e]}" for e in engines if e != "turingserve"]
        L += [table(rows, heads), "",
              f"For reference, vLLM issue #60821 reports **{VLLM_ISSUE_PREFILL[0]}** for an 8,000-token prompt: "
              f"{VLLM_ISSUE_PREFILL[1]}. Re-measure right before publishing (PR #55380 may change this).", ""]
        if plt is not None:
            fig, ax = plt.subplots(figsize=(6, 3.6))
            for e in engines:
                ax.plot(sorted(per[e]), [per[e][k] for k in sorted(per[e])], marker="o", label=NAMES[e])
            ax.set_xlabel("prompt tokens")
            ax.set_ylabel("TTFT median (ms)")
            ax.set_yscale("log")
            ax.legend(fontsize=8)
            save_fig(fig, "prefill_cold_ttft.png")
            L += ["![cold prefill TTFT](figures/prefill_cold_ttft.png)", ""]
    # ---- speculative decoding
    spec = groups.get("spec", [])
    if spec:
        piv = defaultdict(dict)
        for r in spec:
            name = r["meta"]["label"][len("spec-"):]
            for run in r["runs"]:
                piv[name][run["level"]] = run["median"]["output_throughput_tok_s"]
        levels = sorted({lv for v in piv.values() for lv in v})
        order = ["none"] + sorted(k for k in piv if k != "none")
        L += ["## Speculative decoding (ShareGPT, output tok/s and change vs no speculation)", ""]
        rows = []
        for name in order:
            if name not in piv:
                continue
            row = [name]
            for lv in levels:
                v = piv[name].get(lv)
                base = piv.get("none", {}).get(lv)
                row.append("-" if v is None else f"{v:.1f}" + (f" ({(v / base - 1) * 100:+.0f}%)" if base and name != "none" else ""))
            rows.append(row)
        L += [table(rows, ["method"] + [f"c={lv}" for lv in levels]), "",
              "Run size: " + ", ".join(sorted({sample_size(r) for r in spec})) + " (prompts x repetitions).", ""]
        if plt is not None:
            fig, ax = plt.subplots(figsize=(6, 3.6))
            for name in order:
                if name in piv:
                    ax.plot(sorted(piv[name]), [piv[name][k] for k in sorted(piv[name])], marker="o", label=name)
            ax.set_xlabel("concurrent clients")
            ax.set_ylabel("output tokens/s")
            ax.legend(fontsize=7, ncol=2)
            save_fig(fig, "spec_throughput.png")
            L += ["![speculative decoding](figures/spec_throughput.png)", ""]

    # ---- Autopilot
    ap_runs = groups.get("autopilot", [])
    if ap_runs:
        L += ["## Autopilot (Poisson load 0.5 -> 4 -> 0.5 req/s, 120 s each)", ""]
        rows = []
        for r in sorted(ap_runs, key=lambda x: x["meta"]["label"]):
            m = r["runs"][0]["median"]
            rows.append([r["meta"]["label"], fmt(m["output_throughput_tok_s"], 1),
                         f"{m['ttft']['p50'] * 1000:.0f} / {m['ttft']['p90'] * 1000:.0f}",
                         fmt(m["tpot"]["p50"] * 1000, 1), f"{m['goodput_fraction']:.0%}", m["errors"], m["num_requests"]])
        L += [table(rows, ["configuration", "out tok/s", "TTFT p50 / p90 (ms)", "TPOT p50 (ms)", "goodput", "errors",
                           "requests per rep"]), ""]
        log = os.path.join(a.results, "autopilot", "server_autopilot-full.log")
        if os.path.exists(log):
            dec = []
            for line in open(log, errors="replace"):
                if '"autopilot_decision"' in line:
                    try:
                        dec.append(json.loads(line))
                    except json.JSONDecodeError:
                        pass
            if dec:
                c = Counter((d["rule"], d["setting"]) for d in dec)
                L += [f"Autopilot made {len(dec)} decisions in the `full` run: "
                      + ", ".join(f"{rule} {setting} x{n}" for (rule, setting), n in sorted(c.items())) + ".", ""]

    # ---- ramp
    ramp = groups.get("ramp", [])
    for r in ramp:
        L += [f"## Ramp: maximum sustainable rate ({NAMES.get(r['meta']['engine'], r['meta']['engine'])})", ""]
        rows, ok = [], []
        for run in r["runs"]:
            m = run["median"]
            rows.append([run["level"], f"{m['goodput_fraction']:.0%}", m["errors"], fmt(m["output_throughput_tok_s"], 1),
                         fmt(m["ttft"]["p90"] * 1000, 0), fmt(m["tpot"]["p50"] * 1000, 1)])
            if m["goodput_fraction"] >= 0.9 and m["errors"] == 0:
                ok.append(float(run["level"]))
        top = max(float(run["level"]) for run in r["runs"])
        verdict = (f"Every tested rate kept >= 90% goodput with no errors, so the server was not saturated at the highest rate "
                   f"tested (**{top:g} req/s**); its capacity is at least that." if ok and max(ok) == top else
                   f"Highest rate with >= 90% goodput and no errors: **{max(ok) if ok else 'none'} req/s**.")
        L += [table(rows, ["rate (req/s)", "goodput", "errors", "out tok/s", "TTFT p90 (ms)", "TPOT p50 (ms)"]), "", verdict, ""]

    # ---- baselines smoke
    hf = groups.get("hf_smoke", [])
    if hf:
        L += ["## Hugging Face naive baseline (smoke run only)", "",
              "One request at a time behind a global lock; a full sweep was impractical (see the methodology document). "
              "This is a 10-prompt, single-repetition indicator, not a sweep.", ""]
        rows = []
        for r in hf:
            for run in r["runs"]:
                m = run["median"]
                rows.append([run["level"], fmt(m["output_throughput_tok_s"], 1), fmt(m["ttft"]["p50"] * 1000, 0),
                             fmt(m["tpot"]["p50"] * 1000, 1), m["errors"], sample_size(r)])
        L += [table(rows, ["concurrency", "out tok/s", "TTFT p50 (ms)", "TPOT p50 (ms)", "errors", "prompts x reps"]), ""]

    # ---- soak and chaos
    sc = os.path.join(a.results, "soak_chaos")
    soak_path = os.path.join(sc, "soak.json")
    chaos_path = os.path.join(sc, "chaos.txt")
    if os.path.exists(soak_path) or os.path.exists(chaos_path):
        L += ["## Robustness: chaos and soak (T4, Qwen2.5-1.5B)", ""]
        if os.path.exists(chaos_path):
            txt = open(chaos_path, errors="replace").read().strip().splitlines()
            verdict = next((x for x in reversed(txt) if x.startswith(("PASS", "FAIL"))), "no verdict found")
            L += [f"**Chaos test:** {verdict}", "", "```", *[x for x in txt if "requests" in x or x.startswith("final")], "```", ""]
        if os.path.exists(soak_path):
            s = json.load(open(soak_path))
            smp, fin, st = s["samples"], s["final"], s["stats"]
            hours = (smp[-1]["t"] - smp[0]["t"]) / 3600
            ok = (s["rss_growth"] < 0.05 and fin["num_requests_tracked"] == 0 and st["e5xx"] == 0
                  and fin["num_free_blocks"] + fin["num_cached_blocks"] == fin["num_total_blocks"] - 1)
            L += [f"**Soak test:** {'PASS' if ok else 'FAIL'} - {hours:.2f} h of Poisson load, "
                  f"{st['sent']} requests ({st['ok']} ok, {st['e4xx']} 4xx, {st['e5xx']} 5xx, {st['exc']} client exceptions); "
                  f"server RSS growth after minute 10: **{s['rss_growth']:+.2%}** "
                  f"(start {smp[0]['rss'] / 1e6:.0f} MB, end {smp[-1]['rss'] / 1e6:.0f} MB); final state: "
                  f"{fin['num_requests_tracked']} requests tracked, {fin['num_free_blocks']} free + "
                  f"{fin['num_cached_blocks']} cached of {fin['num_total_blocks']} blocks.", ""]
            if plt is not None:
                fig, ax = plt.subplots(figsize=(6, 3.2))
                t0 = smp[0]["t"]
                ax.plot([(x["t"] - t0) / 60 for x in smp], [x["rss"] / 1e6 for x in smp])
                ax.set_xlabel("minutes")
                ax.set_ylabel("server RSS (MB)")
                save_fig(fig, "soak_rss.png")
                L += ["![soak RSS](figures/soak_rss.png)", ""]

    # ---- offline + quality
    off = [json.load(open(q)) for q in glob.glob(os.path.join(a.results, "offline_*.json"))]
    if off:
        L += ["## Offline throughput (fixed 128 output tokens)", "",
              table([[o["engine"], o["gpu"], o["num_prompts"], fmt(o["seconds"], 1), fmt(o["tok_per_s"], 1)] for o in off],
                    ["engine", "GPU", "prompts", "seconds", "tok/s"]), ""]
    qdir = os.path.join(a.results, "quality")
    ppl = [json.load(open(q)) for q in sorted(glob.glob(os.path.join(qdir, "ppl_*.json")))]
    if ppl:
        base = next((x["ppl"] for x in ppl if x["engine"] == "hf"), None) or ppl[0]["ppl"]
        L += ["## Quality: WikiText-2 perplexity", "",
              table([[NAMES.get(q["engine"], q["engine"]), q["dtype"], "INT8 W8A16" if q["int8"] else "-", fmt(q["ppl"], 4),
                      f"{(q['ppl'] / base - 1) * 100:+.3f}%"] for q in ppl],
                    ["engine", "dtype", "weights", "perplexity", "vs first row"]), ""]
    gsm = sorted(glob.glob(os.path.join(qdir, "gsm8k_*_results.json")))
    if gsm:
        rows = []
        for q in gsm:
            d = json.load(open(q))["results"]["gsm8k"]
            rows.append([os.path.basename(q).split("_")[1],
                         f"{d['exact_match,flexible-extract']:.4f} +/- {d['exact_match_stderr,flexible-extract']:.4f}",
                         f"{d['exact_match,strict-match']:.4f} +/- {d['exact_match_stderr,strict-match']:.4f}"])
        L += ["## Quality: GSM8K (5-shot, chat template, 1319 questions)", "",
              table(rows, ["precision", "flexible-extract", "strict-match"]), ""]

    L += ["## Limitations", "",
          "Every published performance number comes from one Kaggle T4 on one stack; relative comparisons are the intended "
          "use. Run sizes differ between experiments (see the methodology document), the Hugging Face baseline is a smoke "
          "run, speculation and Autopilot results are small samples, and prefix caching affects repeated prompts in "
          "repetitions 2 and later. Laptop (GTX 1650) numbers are for correctness only.", ""]
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print("wrote", a.out, f"({len(runs)} result files)")


if __name__ == "__main__":
    main()
